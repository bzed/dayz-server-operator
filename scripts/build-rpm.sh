# Build the dzo rpm from the binary CI already built and the payload the .deb
# ships. Nothing is compiled here; see packaging/rpm/dzo.spec.
#
#   scripts/build-rpm.sh <dzo-binary> <payload-dir> <out-dir>
#
# <payload-dir> is what the deb job uploads as the "dzo-payload" artifact:
#
#   servermods/            dist/servermods/
#   images/                images/
#   contrib/               contrib/
#   html/                  docs/_build/html/
#   man/                   debian/man/ (generated by "dzo gen-man")
#   dzo-cheatsheet.pdf     docs/cheatsheet/dzo-cheatsheet.pdf
#
# The shared files under packaging/common/ and the LICENSE come from this
# checkout, so the rpm cannot drift from the .deb.
#
# Version: the upstream version from the top entry of debian/changelog, with
# the Debian revision as the rpm release. A development build appends
# "+git<commits since the last tag>.<sha>" to that release, the same string
# scripts/debian-snapshot.sh puts in the .deb's version, and rpm orders it the
# same way dpkg does (0.8.2-1 < 0.8.2-1+git43.abc1234 < 0.8.2-2). DZO_RPM_VERSION
# and DZO_RPM_RELEASE override both, for a rebuild without git history.
set -eu

[ $# -eq 3 ] || { echo "usage: $0 <dzo-binary> <payload-dir> <out-dir>" >&2; exit 2; }
binary=$1
payload=$2
out=$3
here=$(cd "$(dirname "$0")/.." && pwd)

[ -f "$binary" ] || { echo "no binary at $binary (run make build-static)" >&2; exit 2; }
for dir in servermods images contrib html man; do
	[ -d "$payload/$dir" ] || { echo "the payload has no $dir/ (see this script's header)" >&2; exit 2; }
done
[ -f "$payload/dzo-cheatsheet.pdf" ] ||
	{ echo "the payload has no dzo-cheatsheet.pdf" >&2; exit 2; }
[ -f "$payload/contrib/dzo/config.yaml" ] ||
	{ echo "the payload has no contrib/dzo/config.yaml" >&2; exit 2; }
[ -d "$payload/contrib/presets/maps" ] ||
	{ echo "the payload has no contrib/presets/maps/" >&2; exit 2; }

# 0.8.2-1 -> version 0.8.2, release 1
changelog_version=$(sed -n '1s/^[^(]*(\([^)]*\)).*/\1/p' "$here/debian/changelog")
[ -n "$changelog_version" ] ||
	{ echo "cannot read the version from debian/changelog" >&2; exit 2; }
upstream=${changelog_version%-*}
revision=${changelog_version##*-}
if [ "$upstream" = "$changelog_version" ]; then
	revision=1
fi

version=${DZO_RPM_VERSION:-$upstream}
if [ -n "${DZO_RPM_RELEASE:-}" ]; then
	release=$DZO_RPM_RELEASE
elif git -C "$here" rev-parse --git-dir >/dev/null 2>&1; then
	last=$(git -C "$here" describe --tags --abbrev=0 2>/dev/null || true)
	if [ -n "$last" ]; then
		count=$(git -C "$here" rev-list --count "$last"..HEAD)
	else
		count=$(git -C "$here" rev-list --count HEAD)
	fi
	if [ "$count" -gt 0 ]; then
		release="$revision+git$count.$(git -C "$here" rev-parse --short=7 HEAD)"
	else
		release=$revision
	fi
else
	# No git history (a source tarball): the version of the top changelog entry.
	release=$revision
fi

work=$(mktemp -d /var/tmp/dzo-rpm.XXXXXX) # not /tmp: it can be a tmpfs, and the payload is large
trap 'rm -rf "$work"' EXIT

# The payload layout the spec's %install reads.
tree=$work/tree
install -d "$tree/presets"
install -m 0755 "$binary" "$tree/dzo"
install -m 0644 "$payload/contrib/dzo/config.yaml" "$tree/config.yaml"
install -m 0755 "$here/packaging/common/dzo-postinst.sh" "$tree/postinst"
install -m 0755 "$here/packaging/common/steamcmd-container" "$tree/steamcmd-container"
install -m 0644 "$here/packaging/common/dzo.tmpfiles" "$tree/dzo.tmpfiles"
install -m 0644 "$payload/dzo-cheatsheet.pdf" "$tree/dzo-cheatsheet.pdf"
cp -a "$payload/servermods" "$tree/servermods"
cp -a "$payload/images" "$tree/images"
cp -a "$payload/contrib/presets/maps" "$tree/presets/maps"
cp -a "$payload/html" "$tree/html"
cp -a "$payload/man" "$tree/man"

install -d "$work/top/SPECS" "$work/top/SOURCES" "$work/top/BUILD" "$work/top/RPMS" "$work/top/SRPMS"
cp "$here/packaging/rpm/dzo.spec" "$work/top/SPECS/dzo.spec"

# rpmbuild reads the version through macros; the spec falls back to 0.0-0 when
# they are not set, so it stays parseable on its own.
rpmbuild -bb \
	--define "_topdir $work/top" \
	--define "dzo_version $version" \
	--define "dzo_release $release" \
	--define "dzo_payload $tree" \
	--define "dzo_license $here/LICENSE" \
	"$work/top/SPECS/dzo.spec"

mkdir -p "$out"
cp "$work"/top/RPMS/x86_64/dzo-*.rpm "$out"/
printf '%s\n' "$out/dzo-$version-$release.x86_64.rpm"
